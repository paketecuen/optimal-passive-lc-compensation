"""Direct GA inverse of ideal compensating current; exact m=2 shortcut.

No FFT and no spectral expansion of the supplied waveforms. N5 voltage is
specified by arbitrary samples. Current is generated by a passive G||C||L
load. Temporal exterior dependence is evaluated by equivalent Gram/linear
algebra operations, without materializing a full Clifford algebra.
"""
import json
from pathlib import Path
import numpy as np

HERE=Path(__file__).resolve().parent
dot=lambda x,y:float(np.mean(x*y))
rms=lambda x:float(np.sqrt(dot(x,x)))

def derivative(N):
    jj=np.arange(N)[:,None]-np.arange(N)[None,:]
    D=np.zeros((N,N)); off=jj!=0
    D[off]=.5*((-1.)**jj[off])/np.sin(np.pi*jj[off]/N)
    return D

def primitive(D,x):
    return np.linalg.lstsq(D,x,rcond=None)[0]

def inverse_current(u,q,D):
    a=D@q; b=primitive(D,q)
    G=np.array([[dot(a,a),dot(a,b)],[dot(a,b),dot(b,b)]])
    h=np.array([dot(u,a),dot(u,b)])
    det=float(np.linalg.det(G))
    # This determinant is ||Dq wedge Jq||^2 in the RMS metric.
    eps=1e-11*max(float(np.prod(np.diag(G))),1e-100)
    if det<=eps:
        return {'nondegenerate':False,'blade_squared':det}
    # Normalize the reciprocal frame before judging a sign. A roundoff-sized
    # positive L at the C-only boundary is not evidence for an interior LC.
    norms=np.sqrt(np.diag(G))
    Gn=G/np.outer(norms,norms)
    voltage_coefficients=np.linalg.solve(Gn,h/norms)
    L,S=voltage_coefficients/norms
    sign_tolerance=64*np.finfo(float).eps*np.linalg.cond(Gn,np.inf)*max(
        float(np.max(np.abs(voltage_coefficients))),rms(u),np.finfo(float).tiny)
    resolved=np.abs(voltage_coefficients)>sign_tolerance
    positive=bool(np.all(voltage_coefficients>sign_tolerance))
    err=u-L*a-S*b
    G3=np.array([[dot(x,y) for y in [u,a,b]] for x in [u,a,b]])
    result={'nondegenerate':True,'blade_squared':det,
            'L_normalized':float(L),'S_normalized':float(S),
            'C_normalized':float(1/S) if resolved[1] else None,
            'compatibility_rms':rms(err),'relative_compatibility':rms(err)/rms(u),
            'triple_blade_squared':float(np.linalg.det(G3)),
            'strictly_positive':positive,
            'component_signs_resolved':bool(np.all(resolved)),
            'near_numerical_boundary':bool(not np.all(resolved)),
            'sign_tolerance_voltage_rms':float(sign_tolerance),
            'sign_test_note':'Signs are resolved in a normalized reciprocal frame; near zero is numerically undecided, not a strict positive component.'}
    result['realizable_ideal_current']=bool(positive and rms(err)<1e-10*rms(u))
    if positive:
        z=S/L
        qt=np.linalg.solve(D@D+z*np.eye(len(u)),D@u)/L
        result.update({'z':float(z),'direct_current_error_rms':rms(qt-q),
                       'L_H_at_50Hz':float(L/(2*np.pi*50)),
                       'C_F_at_50Hz':float(1/(S*2*np.pi*50))})
    return result

def quadratic_data(u,D):
    A=-D@D; v=D@u; j=primitive(D,u)
    K=np.column_stack([u,A@u])
    c=np.linalg.lstsq(K,A@A@u,rcond=None)[0]
    p,s=-float(c[0]),float(c[1])
    return A,v,j,p,s,rms(A@A@u-s*A@u+p*u)

def ideal_m2(u,i,D):
    A,v,j,p,s,closure=quadratic_data(u,D)
    H=np.array([[dot(v,v),dot(v,j)],[dot(j,v),dot(j,j)]])
    rhs=-np.array([dot(i,v),dot(i,j)])
    alpha,beta=np.linalg.solve(H,rhs)
    coefficient_scale=max(abs(alpha),abs(beta),1e-100)
    if abs(alpha)<1e-12*coefficient_scale: alpha=0.
    if abs(beta)<1e-12*coefficient_scale: beta=0.
    q=alpha*v+beta*j
    zero_target=rms(q)<1e-12*max(rms(i),1e-100)
    if zero_target:
        alpha=beta=0.
        q=np.zeros_like(q)
    K=p*alpha*alpha-s*alpha*beta+beta*beta
    scale=max(p*alpha*alpha,abs(s*alpha*beta),beta*beta,1e-100)
    finite=bool(abs(K)>1e-10*scale)
    L=beta/K if finite else None
    S=p*alpha/K if finite else None
    attainable=bool(finite and L>0 and S>0)
    # Complete m2 boundary classification. Temporal quadratic roots identify
    # the two projectors; no transform is applied to the voltage samples.
    roots=np.sort(np.roots([1,-s,p]))
    vv=[]
    for lam,other in [(roots[0],roots[1]),(roots[1],roots[0])]:
        vv.append((A@v-other*v)/(lam-other))
    gainC=max(-dot(i,v),0)**2/dot(v,v)
    gainL=max(-dot(i,j),0)**2/dot(j,j)
    gain1=dot(i,vv[0])**2/dot(vv[0],vv[0])
    gain2=dot(i,vv[1])**2/dot(vv[1],vv[1])
    gains={'C_boundary':gainC,'L_boundary':gainL,
           'resonant_line_1':gain1,'resonant_line_2':gain2,'absent':0.}
    if zero_target: gains={k:0. for k in gains}
    boundary='absent' if zero_target else max(gains,key=gains.get)
    gain=dot(q,q) if attainable else gains[boundary]
    source2=max(0,dot(i,i)-gain)
    inverse=inverse_current(u,q,D)
    result={'alpha':float(alpha),'beta':float(beta),'p':p,'s':s,'K':float(K),
            'zero_target':bool(zero_target),
            'closure_residual_rms':closure,'ideal_current_rms':rms(i+q),
            'original_current_rms':rms(i),'gain_ideal':dot(q,q),
            'L_closed':float(L) if L is not None else None,
            'S_closed':float(S) if S is not None else None,
            'C_closed':float(1/S) if S is not None and abs(S)>1e-12 else None,
            'attains_ideal_with_strict_finite_LC':attainable,
            'best_boundary':boundary,'boundary_gains':{k:float(v) for k,v in gains.items()},
            'global_infimum_rms':float(np.sqrt(source2)),'inverse_test':inverse}
    M0=dot(u,u); M1=dot(v,v); Mn1=dot(j,j); M2=dot(D@v,D@v)
    Delta0=M1*Mn1-M0*M0
    sm=(M2*Mn1-M1*M0)/Delta0
    pm=(M2*M0-M1*M1)/Delta0
    result['closure_from_four_moments']={'M0':M0,'M1':M1,'M_minus1':Mn1,'M2':M2,
        'Delta0':Delta0,'s':sm,'p':pm,'only_new_voltage_moment':'M2=mean((D^2 u)^2)'}
    assert abs(sm-s)<1e-10 and abs(pm-p)<1e-10
    if attainable:
        qreal=np.linalg.solve(D@D+(S/L)*np.eye(len(u)),D@u)/L
        result['realized_current_error_rms']=rms(qreal-q)
        result['realized_source_rms']=rms(i+qreal)
        assert rms(qreal-q)<1e-10
    # Three-new-scalar form using correlations already available in the
    # unconstrained L||C projection.
    a=D@q; b=primitive(D,q)
    R=dot(q,q); Aq=dot(a,a); Bq=dot(b,b)
    d=dot(i,v); e=dot(i,j); Delta=Aq*Bq-R*R
    three={'R_q_squared':R,'Aq_Dq_squared':Aq,'Bq_Jq_squared':Bq,
           'd_i_dot_Du':d,'e_i_dot_Ju':e,'Delta':Delta}
    if Delta>1e-11*max(Aq*Bq,1e-100):
        L3=(Bq*d+R*e)/Delta
        S3=(Aq*e+R*d)/Delta
        three.update({'L':L3,'S':S3,'C':1/S3 if abs(S3)>1e-12 else None})
    result['three_scalar_form']=three
    return result,q

def main():
    u=np.array([1,.2,-.7,-.6,.1]); D=derivative(5)
    A,v,j,p,s,_=quadratic_data(u,D)
    # Passive conductance, capacitor, and inductor in parallel; physical
    # normalization maps C_load=.3/omega and L_load=1/(.7*omega).
    i=.8*u+.3*v+.7*j
    beautiful,q=ideal_m2(u,i,D)
    beautiful.update({'u':u.tolist(),'i':i.tolist(),'q_ideal':q.tolist(),
                      'load':'G=.8 S, normalized C=.3 S and reciprocal L=.7 S in parallel',
                      'U_rms':rms(u),'P':dot(u,i),'source_pf':dot(u,i)/(rms(u)*rms(i+q)),
                      'source_equals_point8u_rms_error':rms(i+q-.8*u)})
    omega=2*np.pi*50
    beautiful['physical_units_at_50Hz']={'R_load_ohm':1/.8,
        'C_load_F':.3/omega,'L_load_H':1/(.7*omega),
        'L_comp_H':3.5/omega,'C_comp_F':1/(6*omega),
        'pole_hz':50*np.sqrt(12/7),
        'normalization':'L_tilde=omega*L [ohm]; S_tilde=1/(omega*C) [ohm]; alpha,beta [siemens]'}
    beautiful['original_pf']=dot(u,i)/(rms(u)*rms(i))
    cases={}
    for name,alpha,beta in [('middle',-.3,-.7),('low_z',1.,5.),('high_z',1.,.5),
                            ('wrong_quadrant',1.,2.),('C_limit',.4,0.),('L_limit',0.,.7),
                            ('rank_one',1.,1.),('q_zero',0.,0.),('opposite_ab_signs',1.,-1.)]:
        target=alpha*v+beta*j
        cases[name]=ideal_m2(u,.8*u-target,D)[0]
    # Independent boundary targets: q=.4 Du and q=.7 Ju have respectively
    # L=0 and S=0. They must never be certified as a strict finite LC.
    # Voltage/time scaling must not change this decision.
    for voltage_scale in (1e-3,1.,1e3):
        for time_scale in (1e-3,1.,1e3):
            for target in (.4*v,.7*j):
                check=inverse_current(voltage_scale*u,voltage_scale*target,time_scale*D)
                assert check['near_numerical_boundary']
                assert not check['realizable_ideal_current']
            check=inverse_current(voltage_scale*u,voltage_scale*q,time_scale*D)
            assert check['realizable_ideal_current']
            assert np.isclose(check['L_normalized'],3.5/time_scale,rtol=1e-10)
            assert np.isclose(check['C_normalized'],1/(6*time_scale),rtol=1e-10)
    # m3 special compatible case, and incompatibility of the nonlinear
    # perturbation from the previous N7 example.
    u3=np.array([1,.2,-.7,-1.1,-.4,.6,.4]); D3=derivative(7)
    A3=-D3@D3; v3=D3@u3
    Q,_=np.linalg.qr(np.column_stack([v3,A3@v3,A3@A3@v3]))
    qt=.6*np.linalg.solve(2.3*np.eye(7)-A3,v3)
    i3=.8*u3-qt
    q3=-Q@(Q.T@i3)
    i3pert=i3+.03*np.roll(u3,1)**3
    i3pert-=np.mean(i3pert)
    q3pert=-Q@(Q.T@i3pert)
    m3={'compatible':inverse_current(u3,q3,D3),'perturbed':inverse_current(u3,q3pert,D3)}
    result={'N5_passive_example':beautiful,'m2_cases':cases,'m3_compatibility':m3,
            'assumptions':'Fixed voltage, ideal scalar time-invariant LC shunt, forced periodic finite model, mean-zero voltage; normalized time theta=omega*t.'}
    (HERE/'direct_series_ga_results.json').write_text(json.dumps(result,indent=2))
    np.savez(HERE/'direct_series_ga_arrays.npz',u=u,i=i,q=q,D=D,A=A,v=v,j=j)
    print('N5 example',json.dumps(beautiful,indent=2))
    print('m2 cases')
    for name,c in cases.items():
        print(name,'attainable',c['attains_ideal_with_strict_finite_LC'],
              'L',c['L_closed'],'S',c['S_closed'],'best boundary',c['best_boundary'],
              'RMS inf',c['global_infimum_rms'])
    print('m3',json.dumps(m3,indent=2))

if __name__=='__main__':main()
