function informe = verificar_fuente_tsc(r,opciones)
%VERIFICAR_FUENTE_TSC KVL de red, balance total y continuidad de su estado.
arguments
    r (1,1) struct
    opciones.InspeccionarModelo (1,1) logical = true
    opciones.AuditarSupervisor (1,1) logical = true
end
assert(isfield(r.config,'Fuente'),'TSCFuente:Contrato','Falta la impedancia de fuente.');
% Reutiliza la auditoria independiente de planta, adquisicion y maniobras.
evalc('base=verificar_tsc_lazo_cerrado(r,InspeccionarModelo=opciones.InspeccionarModelo,AuditarSupervisor=opciones.AuditarSupervisor);');
a=r.trazas; f=r.config.Fuente; t=a.t; h=diff(t);
assert(all(isfinite([a.e;a.iRed;a.energiaRed_J;a.integralFuente_J; ...
    a.integralCarga_J;a.integralPerdidasRed_J])),'TSCFuente:Finito','Trazas no finitas.');
kvl=a.e-f.R_ohm*a.iRed-a.u;
local=f.L_H*diff(a.iRed)-h.*(kvl(1:end-1)+kvl(2:end))/2;
total=a.energia_J+.5*f.L_H*a.iRed.^2;
balance=total-total(1)-a.integralFuente_J+a.integralCarga_J ...
    +a.integralPerdidasRed_J+a.integralPerdidas_J;
power=a.e.*a.iRed-a.u.*a.iCarga-a.perdidas_W-f.R_ohm*a.iRed.^2;
trap=total-total(1)-cumtrapz(t,power);
z=struct('R_ohm',f.R_ohm,'L_H',f.L_H, ...
    'Error_KCL_A',max(abs(a.iRed-a.iCarga-a.iCp-sum(a.iRamas,2))), ...
    'Error_medida_red_A',max(abs(a.iRed-a.iFuente)), ...
    'Error_KVL_local_Vs',max(abs(local)), ...
    'Balance_integrales_J',max(abs(balance)), ...
    'Balance_cuadratura_J',max(abs(trap)), ...
    'Error_inicial_I_A',abs(a.iRed(1)-f.i0_A), ...
    'Error_inicial_VCp_V',abs(a.vCp(1)-r.config.vCp0));
scale=max([1;total]); si=max([1;abs(a.iRed)]); sv=max([1;abs(a.e);abs(a.u)]);
z.Tolerancia_KVL_Vs=2e-4*sv*max(h)+1e-8;
z.Tolerancia_energia_J=2e-5*scale;
z.Tolerancia_cuadratura_J=5e-4*max(scale,trapz(t,abs(power)))+1e-6;
assert(z.Error_KCL_A<1e-9*si && z.Error_medida_red_A<1e-10*si, ...
    'TSCFuente:KCL','La corriente de fuente no cierra el nodo.');
assert(z.Error_KVL_local_Vs<z.Tolerancia_KVL_Vs, ...
    'TSCFuente:KVL','No cierra la ecuacion integral de la impedancia.');
if f.L_H==0
    z.Error_KVL_algebraica_V=max(abs(kvl));
    assert(z.Error_KVL_algebraica_V<1e-9*sv,'TSCFuente:KVL','No cierra la caida resistiva.');
end
assert(z.Balance_integrales_J<z.Tolerancia_energia_J && ...
    z.Balance_cuadratura_J<z.Tolerancia_cuadratura_J, ...
    'TSCFuente:Energia','No cierra el balance total fuente-red-carga-banco.');
assert(z.Error_inicial_I_A<1e-8*si && z.Error_inicial_VCp_V<1e-10*sv, ...
    'TSCFuente:Inicio','Estados iniciales incompatibles con la referencia periodica.');
assert(max(abs(total-a.energiaTotal_J))<1e-10*scale && ...
    max(abs(balance-a.balanceTotal_J))<1e-10*scale, ...
    'TSCFuente:Magnitudes','La energia total declarada es inconsistente.');
if opciones.InspeccionarModelo
    [~,name]=fileparts(r.modelo); load_system(r.modelo);
    cleanup=onCleanup(@()close_system(name,0));
    assert(strcmp(get_param(name,'AlgebraicLoopMsg'),'error'), ...
        'TSCFuente:Estructura','El modelo debe rechazar lazos algebraicos.');
    if f.L_H>0
        assert(strcmp(get_param([name,'/Estado_I_red'],'ExternalReset'),'none'), ...
            'TSCFuente:ResetRed','La corriente de red no debe reiniciarse al conmutar.');
    end
    % Verifica que el supervisor recibe u y no la excitacion e.
    ports=get_param([name,'/Medidas'],'PortConnectivity');
    assert(strcmp(get_param(ports(1).SrcBlock,'Name'),'Tension_bornes'), ...
        'TSCFuente:Medida','El supervisor debe medir la tension en bornes.');
end
informe=struct('passed',true,'red',z,'banco_y_control',base, ...
    'alcance',"Verificacion de la red R-L simulada; no certifica optimalidad del supervisor ni limites de dispositivo.");
end
