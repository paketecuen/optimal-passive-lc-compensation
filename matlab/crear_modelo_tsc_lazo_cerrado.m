function path = crear_modelo_tsc_lazo_cerrado(cfg)
%CREAR_MODELO_TSC_LAZO_CERRADO Supervisor, maniobras y planta en Simulink.
% No reproduce un cronograma externo. La S-function discreta decide usando
% medidas del modelo; cada ejecutor detecta el cero continuo de su corriente.
% VC permanece continuo. El reset de i solo acompana una extincion al cero,
% y se registra su valor previo para cuantificar el residuo numerico.
arguments
    cfg (1,1) struct
end
root=fileparts(mfilename('fullpath')); folder=fullfile(root,'simulink');
if ~isfolder(folder), mkdir(folder); end
name='tsc_lazo_cerrado';
if isfield(cfg,'NombreModelo'), name=char(cfg.NombreModelo); end
assert(isvarname(name),'TSCLazo:NombreModelo','Nombre de modelo invalido.');
path=fullfile(folder,[name,'.slx']);
assert(~bdIsLoaded(name),'TSCLazo:ModeloAbierto','Cierre %s antes de regenerarlo.',name);
load_system('simulink'); new_system(name);
% Los parametros existen antes de crear la S-function: su callback necesita
% cfg para propagar las dimensiones de los puertos durante la construccion.
p=cfg.p;
v=struct('tsc_cfg',cfg,'tm_omega',p.omega,'tm_lambda',p.lambda, ...
    'tm_a1',p.coefTension(1),'tm_a2',p.coefTension(2),'tm_a3',p.coefTension(3), ...
    'tm_Cp',p.Cp_F,'tm_Rp',p.Rp_ohm,'tm_vCp0',cfg.vCp0, ...
    'tm_h',cfg.PasoMaximo_s,'tm_final',cfg.Duracion_s,'tm_carga',cfg.CargaExogena);
for j=1:2
    v.(sprintf('tm_L%d',j))=p.L_H(j); v.(sprintf('tm_C%d',j))=p.C_F(j);
    v.(sprintf('tm_R%d',j))=p.R_ohm(j); v.(sprintf('tm_Rb%d',j))=p.Rb_ohm(j);
    v.(sprintf('tm_vC%d0',j))=cfg.VCInicial_V(j);
end
ws=get_param(name,'ModelWorkspace'); fields=fieldnames(v);
for n=1:numel(fields), assignin(ws,fields{n},v.(fields{n})); end
set_param(name,'Description', ...
    ['Simulacion de lazo cerrado: supervisor temporal discreto, ejecutor ', ...
    'con deteccion continua de corriente cero y planta RC+2LC con perdidas. ', ...
    'No lee cronogramas externos ni llama al motor MATLAB. Fuente impuesta ', ...
    'y carga sintetica exogena. Valvula bidireccional idealizada; no SCR fisico. ', ...
    'El feedback de control usa Memory (un paso mayor del solver).']);
set_param(name,'SolverType','Variable-step','Solver','ode15s', ...
    'RelTol','1e-9','AbsTol','1e-11','MaxStep','tm_h', ...
    'StopTime','tm_final','ReturnWorkspaceOutputs','on','SaveTime','off', ...
    'SaveOutput','off','SignalLogging','off','ZeroCrossControl','UseLocalSettings', ...
    'AlgebraicLoopMsg','error');
add_block('simulink/Sources/Clock',[name,'/Tiempo'],'Position',[25,45,55,65]);
add_block('simulink/User-Defined Functions/Fcn',[name,'/Tension_continua'], ...
    'Expr','tm_lambda*sqrt(2)*(tm_a1*cos(tm_omega*u)+tm_a2*(2*cos(tm_omega*u)^2-1)+tm_a3*(4*cos(tm_omega*u)^3-3*cos(tm_omega*u)))', ...
    'Position',[100,30,330,80]);
add_block('simulink/Sources/From Workspace',[name,'/Carga_exogena'], ...
    'VariableName','tm_carga','SampleTime','0','Interpolate','on', ...
    'OutputAfterFinalValue','Holding final value','Position',[30,115,230,155]);
% Cp con ESR, integrado en el propio modelo.
add_block('simulink/Math Operations/Sum',[name,'/Caida_Rp'], ...
    'Inputs','+-','Position',[390,30,415,70]);
add_block('simulink/Math Operations/Gain',[name,'/Corriente_Cp'], ...
    'Gain','1/tm_Rp','Position',[450,30,510,70]);
add_block('simulink/Math Operations/Gain',[name,'/Derivada_VCp'], ...
    'Gain','1/tm_Cp','Position',[545,30,605,70]);
add_block('simulink/Continuous/Integrator',[name,'/Estado_VCp'], ...
    'InitialCondition','tm_vCp0','Position',[640,30,680,70]);
for j=1:2
    crearRama([name,sprintf('/LC_%d',j)],j);
    crearEjecutor([name,sprintf('/Ejecutor_%d',j)],j,cfg);
    add_block('simulink/Signal Routing/Demux',[name,sprintf('/Diagnostico_%d',j)], ...
        'Outputs','10','Position',[785,295+200*(j-1),790,475+200*(j-1)]);
    add_block('simulink/Sinks/To Workspace',[name,sprintf('/Guardar_ejecutor_%d',j)], ...
        'VariableName',sprintf('ejecutor%d',j),'SaveFormat','Timeseries', ...
        'MaxDataPoints','inf','Position',[850,365+200*(j-1),990,405+200*(j-1)]);
end
add_block('simulink/Math Operations/Sum',[name,'/Corriente_fuente'], ...
    'Inputs','++++','Position',[750,105,775,190]);
% Supervisor causal. Entrada medidas=[u,is,iCp,i1,i2,vC1,vC2].
add_block('simulink/Signal Routing/Mux',[name,'/Medidas'], ...
    'Inputs','7','Position',[1090,50,1095,200]);
add_block('simulink/Signal Routing/Mux',[name,'/VC_actuales'], ...
    'Inputs','2','Position',[1090,245,1095,300]);
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [name,'/Supervisor_temporal'],'FunctionName','tsc_supervisor_sfun', ...
    'Parameters','tsc_cfg','Position',[1170,65,1370,165]);
add_block('simulink/Signal Routing/Demux',[name,'/Ordenes'], ...
    'Outputs','4','Position',[1430,55,1435,180]);
add_block('simulink/Sinks/To Workspace',[name,'/Guardar_supervisor'], ...
    'VariableName','supervisor_diag','SaveFormat','Timeseries','MaxDataPoints','inf', ...
    'SampleTime','tsc_cfg.TsSupervision','Position',[1435,215,1595,255]);
add_block('simulink/Sinks/To Workspace',[name,'/Guardar_ventanas'], ...
    'VariableName','supervisor_ventanas','SaveFormat','Timeseries','MaxDataPoints','inf', ...
    'SampleTime','tsc_cfg.p.T','Position',[1435,280,1595,320]);
% pending=req-applied, salvo solicitud ON ya atendida/rechazada.
add_block('simulink/Signal Routing/Mux',[name,'/Variables_feedback'], ...
    'Inputs','7','Position',[1090,400,1095,560]);
add_block('simulink/User-Defined Functions/Fcn',[name,'/Pendiente_1'], ...
    'Expr','(u(1)>0.5)*(u(3)<0.5)*(u(5)>u(7))-(u(1)<0.5)*(u(3)>0.5)', ...
    'Position',[1140,370,1350,410]);
add_block('simulink/Signal Routing/Mux',[name,'/Variables_feedback_2'], ...
    'Inputs','4','Position',[1090,590,1095,680]);
add_block('simulink/User-Defined Functions/Fcn',[name,'/Pendiente_2'], ...
    'Expr','(u(1)>0.5)*(u(2)<0.5)*(u(3)>u(4))-(u(1)<0.5)*(u(2)>0.5)', ...
    'Position',[1140,610,1350,650]);
add_block('simulink/Math Operations/MinMax',[name,'/Ultima_confirmacion'], ...
    'Function','max','Inputs','2','Position',[1140,485,1230,535]);
add_block('simulink/Signal Routing/Mux',[name,'/Feedback'], ...
    'Inputs','5','Position',[1400,390,1405,560]);
add_block('simulink/Discrete/Memory',[name,'/Feedback_causal'], ...
    'InitialCondition','[0;0;0;0;-1e6]', ...
    'Position',[1460,435,1510,485]);
% Potencia y energia integradas para auditoria independiente.
add_block('simulink/Signal Routing/Mux',[name,'/Variables_potencia'], ...
    'Inputs','7','Position',[380,760,385,920]);
add_block('simulink/User-Defined Functions/Fcn',[name,'/Potencia_entrada'], ...
    'Expr','u(1)*(u(2)+u(4)+u(6))','Position',[420,765,635,805]);
add_block('simulink/User-Defined Functions/Fcn',[name,'/Potencia_disipada'], ...
    'Expr','tm_Rp*u(2)^2+tm_R1*u(4)^2+u(5)^2/tm_Rb1+tm_R2*u(6)^2+u(7)^2/tm_Rb2', ...
    'Position',[420,860,635,900]);
add_block('simulink/Continuous/Integrator',[name,'/Integral_entrada'], ...
    'Position',[670,765,710,805]);
add_block('simulink/Continuous/Integrator',[name,'/Integral_perdidas'], ...
    'Position',[670,860,710,900]);
add_block('simulink/Signal Routing/Mux',[name,'/Registro'], ...
    'Inputs','19','Position',[1640,35,1645,735]);
add_block('simulink/Sinks/To Workspace',[name,'/Guardar'], ...
    'VariableName','registro','SaveFormat','Timeseries','MaxDataPoints','inf', ...
    'Position',[1690,350,1790,390]);
add_line(name,'Tiempo/1','Tension_continua/1');
add_line(name,'Tension_continua/1','Caida_Rp/1');
add_line(name,'Estado_VCp/1','Caida_Rp/2','autorouting','on');
add_line(name,'Caida_Rp/1','Corriente_Cp/1');
add_line(name,'Corriente_Cp/1','Derivada_VCp/1');
add_line(name,'Derivada_VCp/1','Estado_VCp/1');
add_line(name,'Carga_exogena/1','Corriente_fuente/1','autorouting','on');
add_line(name,'Corriente_Cp/1','Corriente_fuente/2','autorouting','on');
for j=1:2
    e=sprintf('Ejecutor_%d',j); d=sprintf('Diagnostico_%d',j); l=sprintf('LC_%d',j);
    add_line(name,'Tension_continua/1',[l,'/1'],'autorouting','on');
    add_line(name,[d,'/1'],[l,'/2'],'autorouting','on');
    add_line(name,[l,'/1'],sprintf('Corriente_fuente/%d',j+2),'autorouting','on');
    inputs={'Tiempo/1',sprintf('Ordenes/%d',j),sprintf('Ordenes/%d',j+2), ...
        'Tension_continua/1',[l,'/3'],[l,'/2']};
    for n=1:6, add_line(name,inputs{n},sprintf('%s/%d',e,n),'autorouting','on'); end
    add_line(name,[e,'/1'],[d,'/1']);
    add_line(name,[e,'/1'],sprintf('Guardar_ejecutor_%d/1',j),'autorouting','on');
end
measurements={'Tension_continua/1','Corriente_fuente/1','Corriente_Cp/1', ...
    'LC_1/1','LC_2/1','LC_1/2','LC_2/2'};
for n=1:7, add_line(name,measurements{n},sprintf('Medidas/%d',n),'autorouting','on'); end
add_line(name,'Medidas/1','Supervisor_temporal/1');
add_line(name,'Feedback_causal/1','Supervisor_temporal/2','autorouting','on');
add_line(name,'LC_1/2','VC_actuales/1','autorouting','on');
add_line(name,'LC_2/2','VC_actuales/2','autorouting','on');
add_line(name,'VC_actuales/1','Supervisor_temporal/3','autorouting','on');
add_line(name,'Supervisor_temporal/1','Ordenes/1');
add_line(name,'Supervisor_temporal/2','Guardar_supervisor/1','autorouting','on');
add_line(name,'Supervisor_temporal/3','Guardar_ventanas/1','autorouting','on');
feedbackVars={'Ordenes/1','Ordenes/2','Diagnostico_1/1','Diagnostico_2/1', ...
    'Ordenes/3','Ordenes/4','Diagnostico_1/3'};
for n=1:7, add_line(name,feedbackVars{n},sprintf('Variables_feedback/%d',n),'autorouting','on'); end
feedbackVars2={'Ordenes/2','Diagnostico_2/1','Ordenes/4','Diagnostico_2/3'};
for n=1:4, add_line(name,feedbackVars2{n},sprintf('Variables_feedback_2/%d',n),'autorouting','on'); end
add_line(name,'Variables_feedback/1','Pendiente_1/1');
add_line(name,'Variables_feedback_2/1','Pendiente_2/1');
add_line(name,'Diagnostico_1/2','Ultima_confirmacion/1','autorouting','on');
add_line(name,'Diagnostico_2/2','Ultima_confirmacion/2','autorouting','on');
feedback={'Diagnostico_1/1','Diagnostico_2/1','Pendiente_1/1','Pendiente_2/1','Ultima_confirmacion/1'};
for n=1:5, add_line(name,feedback{n},sprintf('Feedback/%d',n),'autorouting','on'); end
add_line(name,'Feedback/1','Feedback_causal/1');
power={'Tension_continua/1','Corriente_Cp/1','Estado_VCp/1','LC_1/1','LC_1/2','LC_2/1','LC_2/2'};
for n=1:7, add_line(name,power{n},sprintf('Variables_potencia/%d',n),'autorouting','on'); end
add_line(name,'Variables_potencia/1','Potencia_entrada/1');
add_line(name,'Variables_potencia/1','Potencia_disipada/1');
add_line(name,'Potencia_entrada/1','Integral_entrada/1');
add_line(name,'Potencia_disipada/1','Integral_perdidas/1');
signals={'Tension_continua/1','Carga_exogena/1','Corriente_fuente/1', ...
    'Corriente_Cp/1','Estado_VCp/1','LC_1/1','LC_1/2','LC_2/1','LC_2/2', ...
    'Diagnostico_1/1','Diagnostico_2/1','Integral_entrada/1','Integral_perdidas/1', ...
    'Ordenes/1','Ordenes/2','Ordenes/3','Ordenes/4','Pendiente_1/1','Pendiente_2/1'};
for n=1:19, add_line(name,signals{n},sprintf('Registro/%d',n),'autorouting','on'); end
add_line(name,'Registro/1','Guardar/1');
if isfield(cfg,'Fuente'), agregar_fuente_impedante_tsc(name,cfg); end
if isfield(cfg,'ControlRed'), agregar_control_red_tsc(name,cfg); end
save_system(name,path); close_system(name,0);
end

function crearRama(block,j)
add_block('simulink/Ports & Subsystems/Subsystem',block, ...
    'Position',[390,120+100*(j-1),610,195+100*(j-1)]);
Simulink.SubSystem.deleteContents(block);
add_block('simulink/Ports & Subsystems/In1',[block,'/U'],'Port','1','Position',[20,25,50,45]);
add_block('simulink/Ports & Subsystems/In1',[block,'/ON'],'Port','2','Position',[20,90,50,110]);
add_block('simulink/Signal Routing/Mux',[block,'/Variables'],'Inputs','4','Position',[100,25,105,155]);
add_block('simulink/User-Defined Functions/Fcn',[block,'/Derivada_I'], ...
    'Expr',sprintf('u(2)*(u(1)-tm_R%d*u(3)-u(4))/tm_L%d',j,j),'Position',[150,20,360,60]);
add_block('simulink/User-Defined Functions/Fcn',[block,'/Derivada_VC'], ...
    'Expr',sprintf('(u(2)*u(3)-u(4)/tm_Rb%d)/tm_C%d',j,j),'Position',[150,130,360,170]);
add_block('simulink/Continuous/Integrator',[block,'/Estado_I'], ...
    'InitialCondition','0','ExternalReset','falling','ShowStatePort','on', ...
    'Position',[410,20,450,60]);
add_block('simulink/Continuous/Integrator',[block,'/Estado_VC'], ...
    'InitialCondition',sprintf('tm_vC%d0',j),'Position',[410,130,450,170]);
add_block('simulink/Ports & Subsystems/Out1',[block,'/I'],'Port','1','Position',[520,25,550,45]);
add_block('simulink/Ports & Subsystems/Out1',[block,'/VC'],'Port','2','Position',[520,135,550,155]);
add_block('simulink/Ports & Subsystems/Out1',[block,'/I_pre'], ...
    'Port','3','Position',[520,205,550,225]);
add_line(block,'U/1','Variables/1'); add_line(block,'ON/1','Variables/2');
add_line(block,'Estado_I/1','Variables/3','autorouting','on');
add_line(block,'Estado_VC/1','Variables/4','autorouting','on');
add_line(block,'Variables/1','Derivada_I/1'); add_line(block,'Variables/1','Derivada_VC/1');
add_line(block,'Derivada_I/1','Estado_I/1'); add_line(block,'ON/1','Estado_I/2','autorouting','on');
add_line(block,'Derivada_VC/1','Estado_VC/1');
add_line(block,'Estado_I/1','I/1'); add_line(block,'Estado_VC/1','VC/1');
statePorts=get_param([block,'/Estado_I'],'PortHandles');
prePorts=get_param([block,'/I_pre'],'PortHandles');
add_line(block,statePorts.State,prePorts.Inport,'autorouting','on');
end

function crearEjecutor(block,j,cfg)
add_block('simulink/Ports & Subsystems/Subsystem',block, ...
    'Position',[390,340+200*(j-1),670,455+200*(j-1)]);
Simulink.SubSystem.deleteContents(block);
inputs={'t','requested','scheduled','u','i','vC'};
for n=1:6
    add_block('simulink/Ports & Subsystems/In1',[block,'/',inputs{n}], ...
        'Port',num2str(n),'Position',[20,25+55*(n-1),50,45+55*(n-1)]);
end
add_block('simulink/Signal Routing/Mux',[block,'/Entrada_latch'], ...
    'Inputs','6','Position',[140,145,145,335]);
add_block('simulink/Logic and Bit Operations/Relational Operator',[block,'/Instante_ON'], ...
    'Operator','>=','Position',[95,25,145,75]);
add_block('simulink/Logic and Bit Operations/Logical Operator',[block,'/Orden_ON'], ...
    'Operator','AND','Inputs','2','Position',[190,25,240,75]);
add_block('simulink/Logic and Bit Operations/Logical Operator',[block,'/Orden_OFF'], ...
    'Operator','NOT','Inputs','1','Position',[190,90,240,130]);
add_block('built-in/HitCross',[block,'/Cero_corriente'], ...
    'HitCrossingOffset','0','HitCrossingDirection','either','ShowOutputPort','on', ...
    'Position',[190,365,260,405]);
add_block('simulink/Logic and Bit Operations/Logical Operator',[block,'/Extincion_solicitada'], ...
    'Operator','AND','Inputs','3','Position',[310,85,360,140]);
add_block('simulink/Logic and Bit Operations/Logical Operator',[block,'/Evento'], ...
    'Operator','OR','Inputs','2','Position',[400,25,450,80]);
lat=[block,'/Latch_evento'];
add_block('simulink/Ports & Subsystems/Subsystem',lat,'Position',[500,145,660,245]);
Simulink.SubSystem.deleteContents(lat);
add_block('simulink/Ports & Subsystems/Trigger',[lat,'/Trigger'], ...
    'TriggerType','rising','Position',[115,15,145,35]);
add_block('simulink/Ports & Subsystems/In1',[lat,'/Valores'],'Port','1','Position',[20,100,50,120]);
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function',[lat,'/Actualizar'], ...
    'FunctionName','tsc_ejecutor_sfun', ...
    'Parameters',sprintf('[tm_L%d tm_R%d tsc_cfg.p.limiteDiDt_A_s tm_vC%d0]',j,j,j), ...
    'Position',[100,80,260,140]);
initial=sprintf('[0;-1e6;-1e6;0;0;0;0;%.17g;0;0]',cfg.VCInicial_V(j));
add_block('simulink/Ports & Subsystems/Out1',[lat,'/Estado'], ...
    'Port','1','InitialOutput',initial,'Position',[320,100,350,120]);
add_line(lat,'Valores/1','Actualizar/1'); add_line(lat,'Actualizar/1','Estado/1');
add_block('simulink/Ports & Subsystems/Out1',[block,'/Diagnostico'], ...
    'Port','1','Position',[720,180,750,200]);
% El pulso OFF solo tiene sentido con la rama previamente conectada. Sin
% esta compuerta el HitCrossing puede quedar alto con i=0 mientras esta
% abierta e impedir un ON inmediato por ausencia de un nuevo flanco.
add_block('simulink/Signal Routing/Demux',[block,'/Bit_aplicado'], ...
    'Outputs','[1 9]','Position',[705,260,710,310]);
add_block('simulink/Sinks/Terminator',[block,'/Resto_diagnostico'], ...
    'Position',[760,295,780,315]);
add_block('simulink/Discrete/Memory',[block,'/Estado_previo'], ...
    'InitialCondition','0','Position',[525,340,565,380]);
for n=1:6, add_line(block,[inputs{n},'/1'],sprintf('Entrada_latch/%d',n),'autorouting','on'); end
add_line(block,'t/1','Instante_ON/1','autorouting','on');
add_line(block,'scheduled/1','Instante_ON/2','autorouting','on');
add_line(block,'Instante_ON/1','Orden_ON/1');
add_line(block,'requested/1','Orden_ON/2','autorouting','on');
add_line(block,'requested/1','Orden_OFF/1','autorouting','on');
add_line(block,'i/1','Cero_corriente/1','autorouting','on');
add_line(block,'Orden_OFF/1','Extincion_solicitada/1');
add_line(block,'Cero_corriente/1','Extincion_solicitada/2','autorouting','on');
add_line(block,'Estado_previo/1','Extincion_solicitada/3','autorouting','on');
add_line(block,'Orden_ON/1','Evento/1'); add_line(block,'Extincion_solicitada/1','Evento/2','autorouting','on');
add_line(block,'Evento/1','Latch_evento/Trigger','autorouting','on');
add_line(block,'Entrada_latch/1','Latch_evento/1');
add_line(block,'Latch_evento/1','Diagnostico/1');
add_line(block,'Latch_evento/1','Bit_aplicado/1','autorouting','on');
add_line(block,'Bit_aplicado/1','Estado_previo/1','autorouting','on');
add_line(block,'Bit_aplicado/2','Resto_diagnostico/1');
end
